import os
import subprocess
import re
try:
    from SCons.Script import Import
    Import("env")
except Exception:
    env = None

def get_project_dir():
    if "env" in globals() and env is not None:
        try:
            return env.subst("$PROJECT_DIR")
        except Exception:
            pass
    return os.path.dirname(os.path.abspath(__file__))

def detect_git_info(project_dir):
    def run_git(args):
        try:
            return subprocess.check_output(
                ["git"] + args,
                cwd=project_dir,
                text=True,
                stderr=subprocess.DEVNULL
            ).strip()
        except Exception:
            return ""

    # Upstream candidates to determine merge base with xkain
    base = None
    for ref in ["upstream/main", "upstream/master", "origin/main", "main", "0a3963b5eef2a27bc12b24010567bd98ede6561e"]:
        out = run_git(["merge-base", "HEAD", ref])
        if out:
            base = out
            break

    curr_branch = run_git(["rev-parse", "--abbrev-ref", "HEAD"])
    commit_hash = run_git(["rev-parse", "--short", "HEAD"])

    ignore_patterns = [
        r"^xkain", r"^main$", r"^master$", r"^HEAD$", r"^origin$", r"^upstream",
        r"^cherry-pick/", r"^refs/", r"^origin/main$", r"^origin/master$"
    ]

    def is_ignored(name):
        return any(re.search(pat, name) for pat in ignore_patterns)

    def clean_name(name):
        name = name.strip()
        if name.startswith("remotes/"):
            name = name[8:]
        if name.startswith("origin/"):
            name = name[7:]
        return name

    curr_clean = clean_name(curr_branch)
    merged_branches = []

    if base:
        # 1. Inspect merge commits between base and HEAD
        merges = run_git(["log", f"{base}..HEAD", "--merges", "--pretty=format:%s"]).splitlines()
        for msg in merges:
            matches = re.findall(r"['\"](?:remotes/)?(?:origin/)?([a-zA-Z0-9._/-]+)['\"]", msg)
            for b in matches:
                b_clean = clean_name(b)
                if b_clean and not is_ignored(b_clean) and b_clean not in merged_branches:
                    merged_branches.append(b_clean)

        # 2. Inspect branches merged into HEAD
        merged_refs = run_git(["branch", "-a", "--merged", "HEAD", "--format=%(refname:short)"]).splitlines()
        for b in merged_refs:
            b_clean = clean_name(b)
            if b_clean and not is_ignored(b_clean) and b_clean not in merged_branches:
                ahead = run_git(["rev-list", "--count", f"{base}..{b}"])
                if ahead and ahead.isdigit() and int(ahead) > 0:
                    merged_branches.append(b_clean)

    # Remove current branch from merged_branches if there are multiple entries
    if curr_clean in merged_branches and len(merged_branches) > 1:
        merged_branches.remove(curr_clean)

    # If no merged branches found, but current branch is a custom branch, record current branch
    if not merged_branches and curr_clean and not is_ignored(curr_clean):
        merged_branches.append(curr_clean)

    return {
        "base": base,
        "commit_hash": commit_hash,
        "current_branch": curr_clean,
        "branches": merged_branches
    }

def update_build_header():
    proj_dir = get_project_dir()
    info = detect_git_info(proj_dir)

    branches_str = ",".join(info["branches"])
    commit_str = info["commit_hash"]
    branch_str = info["current_branch"]

    inc_dir = os.path.join(proj_dir, "include")
    os.makedirs(inc_dir, exist_ok=True)
    header_path = os.path.join(inc_dir, "git_build_info.h")

    new_content = f"""// Auto-generated by git_build_info.py - DO NOT EDIT MANUALLY
#ifndef GIT_BUILD_INFO_H
#define GIT_BUILD_INFO_H

#define BUILD_GIT_BRANCH "{branch_str}"
#define BUILD_GIT_COMMIT "{commit_str}"
#define BUILD_CUSTOM_BRANCHES "{branches_str}"

#endif // GIT_BUILD_INFO_H
"""

    existing_content = ""
    if os.path.exists(header_path):
        with open(header_path, "r", encoding="utf-8") as f:
            existing_content = f.read()

    if existing_content != new_content:
        with open(header_path, "w", encoding="utf-8") as f:
            f.write(new_content)
        print(f"[git-info] Updated {header_path}")

    print(f"[git-info] Branch: {branch_str} ({commit_str}) | Branches: {branches_str or 'none'}")

update_build_header()
